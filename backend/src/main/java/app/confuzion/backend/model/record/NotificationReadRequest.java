package app.confuzion.backend.model.record;

import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.media.Schema.RequiredMode;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;

/**
 * Marks the caller's notifications read, up to and including one ID (D-014).
 *
 * @param upTo the newest notification ID the caller has seen
 * @author mcawful
 */
public record NotificationReadRequest(
		@Schema(requiredMode = RequiredMode.REQUIRED, minimum = "1", description = "The newest notification ID the caller has seen. It and every older one of the caller's own are marked read; newer ones stay unread.") @NotNull @Min(1) Long upTo) {
}
